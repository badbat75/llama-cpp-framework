/// A section an earlier version saved, header comment and all, that comment
/// carrying the old word: a comment is a comment, so the section still
/// loads, keys and all. Every machine that upgraded holds such sections.
#[test]
fn a_section_saved_with_the_old_comment_still_loads() {
    const SAVED_BY_AN_EARLIER_VERSION: &str = "\
[Qwen3-8B-Q4_K_M]\r\n\
; Generated by pai-config.\r\n\
; Saving this preset in pai-config rewrites this whole section;\r\n\
; hand-edits to OTHER sections in this file are preserved.\r\n\
\r\n\
model = /models/Qwen3-8B-Q4_K_M.gguf\r\n\
load-on-startup = true\r\n\
ctx-size = 262144\r\n";
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("models.ini");
    fs::write(&path, SAVED_BY_AN_EARLIER_VERSION).unwrap();
    let all = read_model_profiles(&path);
    assert_eq!(all.len(), 1, "{SAVED_BY_AN_EARLIER_VERSION}");
    assert_eq!(all[0].id, "Qwen3-8B-Q4_K_M");
    assert_eq!(all[0].model, "/models/Qwen3-8B-Q4_K_M.gguf");
    assert!(
        all[0].load_on_startup,
        "the key under the old comment loads"
    );
    assert_eq!(all[0].ctx_size, Some(262144));
}

