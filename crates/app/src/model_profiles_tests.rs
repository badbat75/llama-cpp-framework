/// The refusal `pai_core::checks` gives, as the text a save returns.
fn refusal_text(key: &'static str, values: &[&str]) -> String {
    checks::Refusal {
        key,
        values: values.iter().map(|v| v.to_string()).collect(),
    }
    .text()
}

