//! The configurator's logic without a GUI lives in `pai-app` (crates/app),
//! shared by the GUI and the CLI; pai-config keeps only what draws or drives
//! the Slint window. Checked on the files, by path.

use std::path::{Path, PathBuf};

/// The modules that moved to pai-app, as files under `src/` (a module with
/// submodules also has its directory, checked beside it).
const MOVED: [&str; 23] = [
    "bench.rs",
    "devices.rs",
    "gguf.rs",
    "hf.rs",
    "hf_fit.rs",
    "http.rs",
    "hwmon.rs",
    "integrations.rs",
    "kv_cache.rs",
    "linked_files.rs",
    "migration.rs",
    "model_scan.rs",
    "moe_cache.rs",
    "presets.rs",
    "runstate.rs",
    "server_cfg.rs",
    "server_control.rs",
    "server_version.rs",
    "settings.rs",
    "sha256.rs",
    "slot_state.rs",
    "startup.rs",
    "tensor_picker.rs",
];

/// The submodule directories of the moved modules.
const MOVED_DIRS: [&str; 3] = ["bench", "gguf", "hwmon"];

/// Modules whose pure half moved (the other modules of pai-app call it) while
/// a Slint row conversion may stay in pai-config, with the functions that
/// must no longer be defined on the pai-config side.
const SPLIT: [(&str, &[&str]); 2] = [
    (
        "gpu_split.rs",
        &[
            "fn parse_device_list",
            "fn parse_weights",
            "fn block_counts",
        ],
    ),
    ("tensor_override.rs", &["fn parse(", "const KINDS"]),
];

/// The form helpers pai-app's modules (hf) and the CLI take: defined in
/// pai-app, no longer in pai-config's form.rs.
const FORM_HELPERS: [&str; 2] = ["fn fit_allowed(", "fn tri_bool("];

fn crates() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("..")
}

/// Every `.rs` under `dir`.
fn rust_files(dir: &Path, out: &mut Vec<PathBuf>) {
    for entry in std::fs::read_dir(dir).expect("src dir") {
        let path = entry.expect("dir entry").path();
        if path.is_dir() {
            rust_files(&path, out);
        } else if path.extension().is_some_and(|e| e == "rs") {
            out.push(path);
        }
    }
}

/// The `.rs` files under `dir` that define `item` in a code line.
fn defining(dir: &Path, item: &str) -> Vec<PathBuf> {
    let mut files = Vec::new();
    if dir.is_dir() {
        rust_files(dir, &mut files);
    }
    files
        .into_iter()
        .filter(|f| {
            std::fs::read_to_string(f)
                .expect("read source")
                .lines()
                .any(|l| !l.trim_start().starts_with("//") && l.contains(item))
        })
        .collect()
}

#[test]
fn the_gui_free_modules_live_in_pai_app() {
    let app = crates().join("app").join("src");
    let config = crates().join("config").join("src");
    let mut wrong = Vec::new();
    for file in MOVED {
        if !app.join(file).is_file() {
            wrong.push(format!("crates/app/src/{file}: missing"));
        }
        if config.join(file).exists() {
            wrong.push(format!("crates/config/src/{file}: still here"));
        }
    }
    for dir in MOVED_DIRS {
        if !app.join(dir).is_dir() {
            wrong.push(format!("crates/app/src/{dir}/: missing"));
        }
        if config.join(dir).exists() {
            wrong.push(format!("crates/config/src/{dir}/: still here"));
        }
    }
    // gguf's architecture tables are generated by the build script from this
    // file, beside the crate's manifest.
    if !crates().join("app").join("arch_tables.rs").is_file() {
        wrong.push("crates/app/arch_tables.rs: missing".into());
    }
    if crates().join("config").join("arch_tables.rs").exists() {
        wrong.push("crates/config/arch_tables.rs: still here".into());
    }
    assert!(wrong.is_empty(), "\n  {}", wrong.join("\n  "));
}

#[test]
fn the_pure_halves_and_the_form_helpers_live_in_pai_app() {
    let app = crates().join("app").join("src");
    let config = crates().join("config").join("src");
    let mut wrong = Vec::new();
    for (file, items) in SPLIT {
        if !app.join(file).is_file() {
            wrong.push(format!("crates/app/src/{file}: missing"));
        }
        for item in items {
            if defining(&config, item)
                .iter()
                .any(|f| f.file_name().is_some_and(|n| n == file))
            {
                wrong.push(format!("crates/config/src/{file}: still defines `{item}`"));
            }
        }
    }
    for item in FORM_HELPERS {
        if defining(&app, item).is_empty() {
            wrong.push(format!("`{item}`: defined nowhere in crates/app/src"));
        }
        let form = config.join("form.rs");
        if defining(&config, item).contains(&form) {
            wrong.push(format!("crates/config/src/form.rs: still defines `{item}`"));
        }
    }
    assert!(wrong.is_empty(), "\n  {}", wrong.join("\n  "));
}

/// The value of `key` in one table of a manifest, `None` when the table has
/// no such key.
fn table_entry(manifest: &str, table: &str, key: &str) -> Option<String> {
    let mut inside = false;
    for line in manifest.lines() {
        let line = line.split('#').next().unwrap_or("").trim();
        if line.starts_with('[') {
            inside = line == format!("[{table}]");
        } else if inside {
            if let Some((k, v)) = line.split_once('=') {
                if k.trim() == key {
                    return Some(v.trim().to_string());
                }
            }
        }
    }
    None
}

#[test]
fn pai_config_depends_on_pai_app() {
    let manifest =
        std::fs::read_to_string(crates().join("config").join("Cargo.toml")).expect("Cargo.toml");
    let dep = table_entry(&manifest, "dependencies", "pai-app")
        .expect("crates/config/Cargo.toml: no pai-app under [dependencies]");
    assert!(dep.contains(r#"path = "../app""#), "pai-app = {dep}");
}

/// pai-app's test doubles (`server_control::fake`, the backend a test build
/// picks) are compiled for pai-app's own tests only unless a feature turns
/// them on: without it, pai-config's GUI and CLI tests would reach the real
/// manager. Assumed shape: a `test-support` feature, as pai-core has.
#[test]
fn pai_config_tests_take_pai_apps_test_support() {
    let manifest =
        std::fs::read_to_string(crates().join("config").join("Cargo.toml")).expect("Cargo.toml");
    let dep = table_entry(&manifest, "dev-dependencies", "pai-app")
        .expect("crates/config/Cargo.toml: no pai-app under [dev-dependencies]");
    assert!(dep.contains(r#""test-support""#), "pai-app = {dep}");
}

#[test]
fn table_entry_reads_one_table_only() {
    let manifest = r#"
[dependencies]
pai-core = { path = "../core" } # the core
[dev-dependencies]
pai-core = { path = "../core", features = ["test-support"] }
"#;
    assert_eq!(
        table_entry(manifest, "dependencies", "pai-core").as_deref(),
        Some(r#"{ path = "../core" }"#)
    );
    assert!(table_entry(manifest, "dev-dependencies", "pai-core")
        .is_some_and(|v| v.contains("test-support")));
    assert_eq!(table_entry(manifest, "dependencies", "pai-app"), None);
}
