//! build/<os>/config-build.toml: the machine-derived half of the build,
//! written by the configure phase and read by build and package. Hand edits
//! survive until the next configure (GPU targets pruned, an MI card added).

use crate::common::util;
use anyhow::{Context, Result};
use serde::Deserialize;
use std::path::PathBuf;

#[derive(Deserialize, Default)]
pub struct BuildConfig {
    pub dist_root: String,
    pub llama_cpp_dir: String,
    pub hip_path: String,
    pub gpu_targets: String,
    pub build_type: String,
    pub c_compiler: String,
    pub cxx_compiler: String,
    pub linker_type: String,
    pub cuda_host_compiler: String,
    pub build_jobs: u32,
}

pub fn path() -> PathBuf {
    util::build_root().join("config-build.toml")
}

/// The config, or None before the configure phase has run.
pub fn load_optional() -> Result<Option<BuildConfig>> {
    let p = path();
    if !p.exists() {
        return Ok(None);
    }
    let text = std::fs::read_to_string(&p).with_context(|| format!("reading {}", p.display()))?;
    Ok(Some(toml::from_str(&text).with_context(|| format!("parsing {}", p.display()))?))
}

pub fn load() -> Result<BuildConfig> {
    load_optional()?
        .with_context(|| format!("build/{}/config-build.toml not found. Run cargo run -p xtask -- configure first.", util::OS_DIR))
}

fn q(s: &str) -> String {
    toml::Value::String(s.to_string()).to_string()
}

impl BuildConfig {
    pub fn save(&self) -> Result<()> {
        let text = format!(
            r#"# Generated by the configure phase (cargo run -p xtask -- configure); re-run it to refresh.

# Paths
# dist_root: where the SDK dists live, <root>/<Name>/<Version>/{os}.
# hip_path is the newest ROCm dist under it at configure time; the build
# resolves the CUDA Toolkit, NCCL and the Vulkan SDK there itself. Change it
# with cargo run -p xtask -- configure --dist-root <path>, not by hand.
dist_root = {dist_root}
llama_cpp_dir = {llama}
hip_path = {hip}

# Build settings
# gpu_targets: DERIVED from the installed ROCm dist (the archs it ships BLAS
# kernels for, minus the data-center gfx9xx and gfx125x, plus the Ryzen iGPU
# archs). Re-run cargo run -p xtask -- configure after a ROCm dist bump to refresh.
# Hand-edit to prune (~56 MiB of libggml-hip.so per arch) or to add an MI card.
gpu_targets = {targets}
build_type = {build_type}
c_compiler = {cc}
cxx_compiler = {cxx}
# "LLD" = link with the lld next to the compiler (-fuse-ld=lld); blank =
# the toolchain's default linker.
linker_type = {linker}
# Host compiler nvcc drives for the CUDA backend.
cuda_host_compiler = {cuda_host}
# Parallel build jobs: 3/4 of logical cores, never all of them, so at least
# one stays free during a long CUDA/HIP compile (0 = use all cores).
build_jobs = {jobs}
"#,
            os = util::OS_DIR,
            dist_root = q(&self.dist_root),
            llama = q(&self.llama_cpp_dir),
            hip = q(&self.hip_path),
            targets = q(&self.gpu_targets),
            build_type = q(&self.build_type),
            cc = q(&self.c_compiler),
            cxx = q(&self.cxx_compiler),
            linker = q(&self.linker_type),
            cuda_host = q(&self.cuda_host_compiler),
            jobs = self.build_jobs,
        );
        let p = path();
        std::fs::create_dir_all(p.parent().unwrap())?;
        std::fs::write(&p, text).with_context(|| format!("writing {}", p.display()))
    }
}
