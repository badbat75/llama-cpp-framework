/// Writes [`files`] under `stage`, mode 0644.
pub fn stage(stage: &Path) -> Result<()> {
    for (rel, text) in files() {
        let p = stage.join(rel);
        std::fs::create_dir_all(p.parent().unwrap())?;
        std::fs::write(&p, text).with_context(|| format!("writing {}", p.display()))?;
        set_mode(&p, 0o644)?;
    }
    Ok(())
}

/// The `.deb` maintainer scripts of a package, by name (`postinst`,
/// `prerm`, `postrm`); none for a package without system files.
pub fn deb_scripts(c: Component) -> Vec<(&'static str, String)> {
    if c == Component::Bff {
        return bff_deb_scripts();
    }
    if c == Component::Llama {
        return engine_deb_scripts();
    }
    if c != Component::Core {
        return Vec::new();
    }
    let head = format!("#!/bin/sh\nset -e\n{}\n", header("#"));
    // debhelper's autoscripts postinst-sysusers, postinst-systemd-enable and
    // postinst-systemd-restart, plus the bus policy reload. On an upgrade a
    // restart, not a start: the prerm of a release that did not stop the
    // manager before an upgrade left it running.
    let postinst = format!(
        r#"{head}if [ "$1" = "configure" ] || [ "$1" = "abort-upgrade" ] || [ "$1" = "abort-deconfigure" ] || [ "$1" = "abort-remove" ] ; then
	systemd-sysusers ${{DPKG_ROOT:+--root="$DPKG_ROOT"}} private-ai.conf

	# was-enabled is true on a first install, false once disabled.
	if deb-systemd-helper --quiet was-enabled {MANAGER_SERVICE}; then
		deb-systemd-helper enable {MANAGER_SERVICE} >/dev/null || true
	else
		deb-systemd-helper update-state {MANAGER_SERVICE} >/dev/null || true
	fi

	if [ -d /run/systemd/system ]; then
		systemctl --system daemon-reload >/dev/null || true
		# The manager owns its name only once the bus has read the policy.
		{RELOAD_BUS} >/dev/null || true
		if [ -n "$2" ]; then
			deb-systemd-invoke restart {MANAGER_SERVICE} >/dev/null || true
		else
			deb-systemd-invoke start {MANAGER_SERVICE} >/dev/null || true
		fi
	fi
fi
"#
    );
    // Stopped before its files are replaced, on upgrade as on removal.
    let prerm = format!(
        r#"{head}{STOPPING} ; then
	deb-systemd-invoke stop {MANAGER_SERVICE} >/dev/null || true
fi
"#
    );
    // postrm-systemd-reload-only and postrm-systemd. The configuration and
    // the service user's data are kept, even on purge.
    let postrm = format!(
        r#"{head}if [ "$1" = remove ] && [ -d /run/systemd/system ] ; then
	systemctl --system daemon-reload >/dev/null || true
fi

if [ "$1" = "purge" ]; then
	if [ -x "/usr/bin/deb-systemd-helper" ]; then
		deb-systemd-helper purge {MANAGER_SERVICE} >/dev/null || true
	fi
fi
"#
    );
    vec![("postinst", postinst), ("prerm", prerm), ("postrm", postrm)]
}

