/// The test that opens a prerm's stop: before the package's files are
/// replaced (deb-prerm(5): `upgrade`, `remove`, `deconfigure`), never in a
/// chroot install or without systemd running.
const STOPPING: &str = r#"if [ -z "$DPKG_ROOT" ] && { [ "$1" = upgrade ] || [ "$1" = remove ] || [ "$1" = deconfigure ] ; } && [ -d /run/systemd/system ]"#;

/// Records the active instances in [`RECORD`], one unit per line, and stops
/// them: the body of the engine's prerm and `.rpm` %pre.
fn record_and_stop_instances(indent: &str) -> String {
    format!(
        "{indent}systemctl list-units --plain --no-legend --state=active {INSTANCES} | while read -r unit _; do echo \"$unit\"; done > {RECORD} || true\n\
         {indent}systemctl stop {INSTANCES} >/dev/null || true\n"
    )
}

/// Starts each instance [`RECORD`] names: the body of the engine's postinst
/// and `.rpm` %posttrans.
fn start_recorded_instances(indent: &str) -> String {
    format!(
        "{indent}if [ -f {RECORD} ]; then\n\
         {indent}\twhile read -r unit; do\n\
         {indent}\t\tsystemctl start \"$unit\" >/dev/null || true\n\
         {indent}\tdone < {RECORD}\n\
         {indent}fi\n"
    )
}

/// Copies each shipped default into [`ENGINE_ETC`] when it is missing, never
/// over an existing file: the server file 0640 with the group private-ai
/// once that group exists (the core package creates it), else 0644 root:root
/// until the manager's first write; the presets 0644. With `chroot` (the
/// `.deb`), every path is under `$DPKG_ROOT` and a chroot install asks the
/// host for no group: the server file is copied 0644 there.
fn copy_missing_defaults(indent: &str, chroot: bool) -> String {
    let server = "server@default.ini";
    let presets = "presets.ini";
    let (root, host) = if chroot {
        ("$DPKG_ROOT", r#"[ -z "$DPKG_ROOT" ] && "#)
    } else {
        ("", "")
    };
    let etc = format!("\"{root}{ENGINE_ETC}\"");
    let share = format!("\"{root}{ENGINE_DEFAULTS}\"");
    format!(
        "{indent}install -d -m 0755 {etc}\n\
         {indent}if [ ! -e {etc}/{server} ]; then\n\
         {indent}\tif {host}getent group private-ai >/dev/null; then\n\
         {indent}\t\tinstall -m 0640 -g private-ai {share}/{server} {etc}/{server}\n\
         {indent}\telse\n\
         {indent}\t\tinstall -m 0644 {share}/{server} {etc}/{server}\n\
         {indent}\tfi\n\
         {indent}fi\n\
         {indent}if [ ! -e {etc}/{presets} ]; then\n\
         {indent}\tinstall -m 0644 {share}/{presets} {etc}/{presets}\n\
         {indent}fi\n"
    )
}

/// The engine's `.deb` maintainer scripts: its running instances recorded
/// and stopped before its files are replaced, and started again, each by
/// name, once the new files are in place; the record forgotten on removal.
/// On configure the missing defaults are copied first; a purge deletes the
/// engine's configuration, a removal keeps it.
fn engine_deb_scripts() -> Vec<(&'static str, String)> {
    let head = format!("#!/bin/sh\nset -e\n{}\n", header_of(Component::Llama, "#"));
    let postinst = format!(
        r#"{head}if [ "$1" = "configure" ] || [ "$1" = "abort-upgrade" ] || [ "$1" = "abort-deconfigure" ] || [ "$1" = "abort-remove" ] ; then
	if [ "$1" = "configure" ]; then
{copy}	fi
	if [ -d /run/systemd/system ]; then
		systemctl --system daemon-reload >/dev/null || true
{start}	fi
	if [ -z "$DPKG_ROOT" ]; then
		rm -f {RECORD}
	fi
fi
"#,
        copy = copy_missing_defaults("\t\t", true),
        start = start_recorded_instances("\t\t")
    );
    let prerm = format!(
        "{head}{STOPPING} ; then\n{}fi\n",
        record_and_stop_instances("\t")
    );
    let postrm = format!(
        r#"{head}if [ "$1" = remove ]; then
	rm -f {RECORD}
	if [ -d /run/systemd/system ]; then
		systemctl --system daemon-reload >/dev/null || true
	fi
fi

if [ "$1" = "purge" ]; then
	rm -rf "$DPKG_ROOT{ENGINE_ETC}"
fi
"#
    );
    vec![("postinst", postinst), ("prerm", prerm), ("postrm", postrm)]
}

/// Writes [`deb_scripts`] into `root/DEBIAN`, mode 0755.
pub fn write_deb_scripts(root: &Path, c: Component) -> Result<()> {
    let scripts = deb_scripts(c);
    if scripts.is_empty() {
        return Ok(());
    }
    let dir = root.join("DEBIAN");
    std::fs::create_dir_all(&dir)?;
    for (name, text) in scripts {
        let p = dir.join(name);
        std::fs::write(&p, text).with_context(|| format!("writing {}", p.display()))?;
        set_mode(&p, 0o755)?;
    }
    Ok(())
}

/// The `.deb` Depends the maintainer scripts need, empty when none.
pub fn deb_depends(c: Component) -> &'static str {
    // What dh_installsysusers adds for systemd-sysusers; deb-systemd-helper
    // and deb-systemd-invoke come with init-system-helpers, which is Essential.
    if c == Component::Core || c == Component::Bff {
        "systemd | systemd-standalone-sysusers | systemd-sysusers"
    } else {
        ""
    }
}

/// The `.rpm` scriptlets of a package (`%post`, `%preun`, `%postun`,
/// `%posttrans`), empty for a package without system files.
pub fn rpm_scriptlets(c: Component) -> String {
    if c == Component::Bff {
        return bff_rpm_scriptlets();
    }
    if c == Component::Llama {
        return engine_rpm_scriptlets();
    }
    if c != Component::Core {
        return String::new();
    }
    // Fedora's systemd macros (systemd's src/rpm/macros.systemd.in) written
    // out, since they are not defined where the packages are built. The
    // manager is stopped in the new package's %pre on an upgrade, enabled
    // on the first install, and (re)started in %posttrans, once the old
    // package's files are gone.
    format!(
        r#"%pre
if [ $1 -ge 2 ] && [ -d /run/systemd/system ]; then
    systemctl stop {MANAGER_SERVICE} || :
fi

%post
systemd-sysusers private-ai.conf || :
if [ $1 -eq 1 ]; then
    systemctl enable {MANAGER_SERVICE} || :
fi

%preun
if [ $1 -eq 0 ]; then
    if [ -d /run/systemd/system ]; then
        systemctl disable --now {MANAGER_SERVICE} || :
    else
        systemctl disable {MANAGER_SERVICE} || :
    fi
fi

%postun
if [ -d /run/systemd/system ]; then
    systemctl daemon-reload || :
fi

%posttrans
if [ -d /run/systemd/system ]; then
    systemctl daemon-reload || :
    {RELOAD_BUS} || :
    if systemctl is-enabled --quiet {MANAGER_SERVICE}; then
        systemctl restart {MANAGER_SERVICE} || :
    fi
fi

"#
    )
}

