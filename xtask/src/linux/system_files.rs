/// The D-Bus policy of the manager's bus name.
pub fn dbus_policy() -> String {
    format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         <!DOCTYPE busconfig PUBLIC \"-//freedesktop//DTD D-BUS Bus Configuration 1.0//EN\"\n \
         \"http://www.freedesktop.org/standards/dbus/1.0/busconfig.dtd\">\n\
         <!--\n{}  Only root owns the name; everyone may call it, polkit decides in each call.\n-->\n\
         <busconfig>\n  \
           <policy user=\"root\">\n    \
             <allow own=\"{BUS_NAME}\"/>\n  \
           </policy>\n  \
           <policy context=\"default\">\n    \
             <allow send_destination=\"{BUS_NAME}\"/>\n  \
           </policy>\n\
         </busconfig>\n",
        header(" ")
    )
}

/// The polkit actions the manager checks.
pub fn polkit_policy() -> String {
    let action = |id: &str, description: &str, message: &str, defaults: [&str; 3]| {
        format!(
            "  <action id=\"org.privateai.manager.{id}\">\n    \
               <description>{description}</description>\n    \
               <message>{message}</message>\n    \
               <defaults>\n      \
                 <allow_any>{}</allow_any>\n      \
                 <allow_inactive>{}</allow_inactive>\n      \
                 <allow_active>{}</allow_active>\n    \
               </defaults>\n  \
             </action>\n",
            defaults[0], defaults[1], defaults[2]
        )
    };
    format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
         <!DOCTYPE policyconfig PUBLIC \"-//freedesktop//DTD polkit Policy Configuration 1.0//EN\"\n\
         \"http://www.freedesktop.org/software/polkit/policyconfig-1.dtd\">\n\
         <!--\n{}-->\n\
         <policyconfig>\n  \
           <vendor>Private AI Framework</vendor>\n\
         {}{}\
         </policyconfig>\n",
        header(" "),
        action(
            "control",
            "Start, stop and restart the llama.cpp servers",
            "Authentication is required to start, stop or restart a llama.cpp server",
            ["auth_admin", "auth_admin", "yes"],
        ),
        action(
            "configure",
            "Change the configuration of the llama.cpp servers",
            "Authentication is required to change the configuration of the llama.cpp servers",
            ["auth_admin_keep", "auth_admin_keep", "auth_admin_keep"],
        ),
    )
}

