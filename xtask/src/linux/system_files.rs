/// The engine's tmpfiles.d entry: the instances' shared default models
/// folder (`paths::instance_models_dir`), readable by everyone, written by
/// the service user. Not a StateDirectory= of the instance unit, whose one
/// StateDirectoryMode= keeps the service user's home 0750.
fn engine_tmpfiles() -> String {
    format!(
        "{}d /var/lib/llama.cpp 0755 root root -\n\
         d /var/lib/llama.cpp/models 0755 private-ai private-ai -\n",
        header_of(Component::Llama, "#")
    )
}

/// Applies the engine's tmpfiles.d entry from a `.deb` postinst, as
/// debhelper's autoscript postinst-init-tmpfiles does, behind `indent`.
fn deb_create_tmpfiles(indent: &str) -> String {
    format!(
        "{indent}if [ -x \"$(command -v systemd-tmpfiles)\" ]; then\n\
         {indent}\tsystemd-tmpfiles ${{DPKG_ROOT:+--root=\"$DPKG_ROOT\"}} --create {TMPFILES_NAME} || true\n\
         {indent}fi\n"
    )
}

/// `private-ai-manager.service`: `pai-manager serve`, as root.
pub fn manager_unit() -> String {
    format!(
        "{}# Local changes go in a drop-in: systemctl edit {MANAGER_SERVICE}\n\
         \n\
         [Unit]\n\
         Description=Private AI Framework manager\n\
         \n\
         [Service]\n\
         Type=dbus\n\
         BusName={BUS_NAME}\n\
         ExecStart={MANAGER_EXE} serve\n\
         # The services' home: a blank ModelsDir means the same to the manager as to the instances.\n\
         Environment=HOME=/var/lib/private-ai\n\
         # The framework's (bff.ini) and the engine's (the instance files).\n\
         ConfigurationDirectory=private-ai llama.cpp\n\
         ConfigurationDirectoryMode=0755\n\
         Restart=on-failure\n\
         \n\
         [Install]\n\
         WantedBy=multi-user.target\n",
        header("#")
    )
}

/// `llama.cpp@.service`: `pai-manager run-instance %i`, as the service user.
pub fn instance_unit() -> String {
    format!(
        "{}# Started and stopped through the manager; at boot once enabled\n\
         # (systemctl enable llama.cpp@<id>, the configurator's start at boot).\n\
         \n\
         [Unit]\n\
         Description=llama.cpp server %i (Private AI Framework)\n\
         After=network-online.target\n\
         Wants=network-online.target\n\
         # Ordering only, no requirement: the manager renders each instance's\n\
         # models@<id>.ini at its own start, so an enabled instance that starts\n\
         # at boot starts once that render stands.\n\
         After=private-ai-manager.service\n\
         # The launcher is the framework's, which this package does not require.\n\
         ConditionFileIsExecutable={MANAGER_EXE}\n\
         # The one name another unit orders itself after (`After=` takes no\n\
         # globs): ordering only, the target pulls nothing in.\n\
         Before=llama.cpp.target\n\
         \n\
         [Service]\n\
         Type=exec\n\
         User=private-ai\n\
         Group=private-ai\n\
         SupplementaryGroups=render video\n\
         # The user's home and the launcher's data root under it.\n\
         StateDirectory=private-ai private-ai/.local/share/private-ai\n\
         StateDirectoryMode=0750\n\
         ExecStart={MANAGER_EXE} run-instance %i\n\
         # The start job ends once the router answers: systemd counts the start\n\
         # done when this command exits and takes it into account for the\n\
         # Before=/After= ordering (systemd.service(5)), so a unit ordered after\n\
         # this instance starts once the server listens. No `-` prefix: a manager\n\
         # with no `wait-ready` answers a non-zero code, and the engine's package\n\
         # keeps that pair honest (its Breaks and Conflicts on an older core,\n\
         # `linux::package`).\n\
         ExecStartPost={MANAGER_EXE} wait-ready %i\n\
         # The backstop behind the command's own deadline: a systemd start\n\
         # timeout is abnormal, and Restart=on-abnormal would restart a load\n\
         # that is only slow, so the command's deadline must come first.\n\
         TimeoutStartSec=11min\n\
         # The stop first saves the conversation snapshots; this bounds that save.\n\
         ExecStop={MANAGER_EXE} save-slots %i\n\
         TimeoutStopSec=300\n\
         Restart=on-abnormal\n\
         RestartSec=5\n\
         \n\
         [Install]\n\
         WantedBy=multi-user.target\n",
        header_of(Component::Llama, "#")
    )
}

/// `llama.cpp.target`: the one name every instance is ordered before, so
/// another unit has one name to order itself after (`After=` takes no globs).
/// Static: no `[Install]`, it is pulled into the boot transaction by the link
/// the package ships ([`TARGET_LINK`], the way systemd's own static units
/// are), and no `PartOf=`: stopping the target must not stop the instances,
/// which the manager starts and stops one by one.
fn llama_cpp_target() -> String {
    format!(
        "{}# Ordered before by every instance (llama.cpp@.service, Before=).\n\
         # Reached at boot once every enabled instance's start has ended, the\n\
         # ExecStartPost= included. Nothing enables it and it starts nothing.\n\
         \n\
         [Unit]\n\
         Description=llama.cpp servers (Private AI Framework)\n",
        header_of(Component::Llama, "#")
    )
}

