/// The polkit rules of the manager's actions: `configure` for the members of
/// the administrators' group with their own password, refused to everyone
/// else; any other action left to its defaults. ECMAScript 5, which polkit
/// runs (polkit(8) "AUTHORIZATION RULES").
pub fn polkit_rules() -> String {
    format!(
        "{}\n\
         polkit.addRule(function (action, subject) {{\n    \
             if (action.id == \"org.privateai.manager.configure\") {{\n        \
                 return subject.isInGroup(\"{ADMIN_GROUP}\")\n            \
                     ? polkit.Result.AUTH_SELF_KEEP\n            \
                     : polkit.Result.NO;\n    \
             }}\n\
         }});\n",
        header("//")
    )
}

/// Where the core package ships the PAM service of the web sign-in, under
/// the package root (the manager's `accounts::SERVICE`).
pub const PAM_SERVICE: &str = "etc/pam.d/private-ai";

/// The header of the PAM service: a conffile, kept by an upgrade once edited.
fn pam_header() -> String {
    format!(
        "#%PAM-1.0\n\
         # The web sign-in of the Private AI Framework (pai-manager). Installed by\n\
         # the {} package, generated by its package phase\n\
         # (xtask/src/linux/system_files.rs). A configuration file: an upgrade\n\
         # keeps a local edit.\n",
        Component::Core.package()
    )
}

/// The PAM service of the web sign-in in the `.deb`: Debian's common stacks.
pub fn pam_deb() -> String {
    format!(
        "{}@include common-auth\n\
         @include common-account\n",
        pam_header()
    )
}

/// The PAM service of the web sign-in in the `.rpm`: Fedora's and RHEL's
/// system-auth.
pub fn pam_rpm() -> String {
    format!(
        "{}auth       include      system-auth\n\
         account    include      system-auth\n",
        pam_header()
    )
}

/// Writes `text` as the PAM service under `root`, mode 0644.
fn write_pam(root: &Path, text: &str) -> Result<()> {
    let p = root.join(PAM_SERVICE);
    std::fs::create_dir_all(p.parent().unwrap())?;
    std::fs::write(&p, text).with_context(|| format!("writing {}", p.display()))?;
    set_mode(&p, 0o644)
}

/// Writes the `.rpm`-only files of package `c` under `root`: the core's PAM
/// service, over the `.deb` text a `.deb` build of the same tree may have
/// left.
pub fn write_rpm_files(root: &Path, c: Component) -> Result<()> {
    if c == Component::Core {
        write_pam(root, &pam_rpm())?;
    }
    Ok(())
}

/// Writes [`files`] under `stage`, mode 0644, and the target's
/// `multi-user.target.wants/` link, as a symlink to the unit beside it (a copy
/// of the text would drift from the unit; both formats pack a symlink).
pub fn stage(stage: &Path) -> Result<()> {
    for (rel, text) in files() {
        let p = stage.join(rel);
        std::fs::create_dir_all(p.parent().unwrap())?;
        std::fs::write(&p, text).with_context(|| format!("writing {}", p.display()))?;
        set_mode(&p, 0o644)?;
    }
    let link = stage.join(TARGET_LINK);
    std::fs::create_dir_all(link.parent().unwrap())?;
    let unit = TARGET_UNIT.rsplit('/').next().unwrap_or(TARGET_UNIT);
    std::os::unix::fs::symlink(Path::new("..").join(unit), &link)
        .with_context(|| format!("linking {}", link.display()))
}

/// The `.deb` maintainer scripts of a package, by name (`postinst`,
/// `prerm`, `postrm`); none for a package without system files.
pub fn deb_scripts(c: Component) -> Vec<(&'static str, String)> {
    if c == Component::Bff {
        return bff_deb_scripts();
    }
    if c == Component::Llama {
        return engine_deb_scripts();
    }
    if c != Component::Core {
        return Vec::new();
    }
    let head = format!("#!/bin/sh\nset -e\n{}\n", header("#"));
    // debhelper's autoscripts postinst-sysusers, postinst-systemd-enable and
    // postinst-systemd-restart, plus the bus policy reload. On an upgrade a
    // restart, not a start: the prerm of a release that did not stop the
    // manager before an upgrade left it running.
    let postinst = format!(
        r#"{head}if [ "$1" = "configure" ] || [ "$1" = "abort-upgrade" ] || [ "$1" = "abort-deconfigure" ] || [ "$1" = "abort-remove" ] ; then
	systemd-sysusers ${{DPKG_ROOT:+--root="$DPKG_ROOT"}} private-ai.conf
	# The engine's shared models folder, owned by the user just created.
{tmpfiles}
	# was-enabled is true on a first install, false once disabled.
	if deb-systemd-helper --quiet was-enabled {MANAGER_SERVICE}; then
		deb-systemd-helper enable {MANAGER_SERVICE} >/dev/null || true
	else
		deb-systemd-helper update-state {MANAGER_SERVICE} >/dev/null || true
	fi

	if [ -d /run/systemd/system ]; then
		systemctl --system daemon-reload >/dev/null || true
		# The manager owns its name only once the bus has read the policy.
		{RELOAD_BUS} >/dev/null || true
		if [ -n "$2" ]; then
			deb-systemd-invoke restart {MANAGER_SERVICE} >/dev/null || true
		else
			deb-systemd-invoke start {MANAGER_SERVICE} >/dev/null || true
		fi
	fi
fi
"#,
        tmpfiles = deb_create_tmpfiles("\t")
    );
    // Stopped before its files are replaced, on upgrade as on removal.
    let prerm = format!(
        r#"{head}{STOPPING} ; then
	deb-systemd-invoke stop {MANAGER_SERVICE} >/dev/null || true
fi
"#
    );
    // postrm-systemd-reload-only and postrm-systemd. The configuration and
    // the service user's data are kept, even on purge.
    let postrm = format!(
        r#"{head}if [ "$1" = remove ] && [ -d /run/systemd/system ] ; then
	systemctl --system daemon-reload >/dev/null || true
fi

if [ "$1" = "purge" ]; then
	if [ -x "/usr/bin/deb-systemd-helper" ]; then
		deb-systemd-helper purge {MANAGER_SERVICE} >/dev/null || true
	fi
fi
"#
    );
    vec![("postinst", postinst), ("prerm", prerm), ("postrm", postrm)]
}

/// The bff's `.deb` maintainer scripts: dh_installsysusers' and
/// dh_installsystemd's for one unit (postinst-sysusers,
/// postinst-systemd-enable, postinst-systemd-restart, prerm-systemd-restart,
/// postrm-systemd-reload-only, postrm-systemd).
fn bff_deb_scripts() -> Vec<(&'static str, String)> {
    let head = format!("#!/bin/sh\nset -e\n{}\n", header_of(Component::Bff, "#"));
    let postinst = format!(
        r#"{head}if [ "$1" = "configure" ] || [ "$1" = "abort-upgrade" ] || [ "$1" = "abort-deconfigure" ] || [ "$1" = "abort-remove" ] ; then
	systemd-sysusers ${{DPKG_ROOT:+--root="$DPKG_ROOT"}} private-ai-bff.conf

	# was-enabled is true on a first install, false once disabled.
	if deb-systemd-helper --quiet was-enabled {BFF_SERVICE}; then
		deb-systemd-helper enable {BFF_SERVICE} >/dev/null || true
	else
		deb-systemd-helper update-state {BFF_SERVICE} >/dev/null || true
	fi

	if [ -d /run/systemd/system ]; then
		systemctl --system daemon-reload >/dev/null || true
		if [ -n "$2" ]; then
			deb-systemd-invoke restart {BFF_SERVICE} >/dev/null || true
		else
			deb-systemd-invoke start {BFF_SERVICE} >/dev/null || true
		fi
	fi
fi
"#
    );
    let prerm = format!(
        r#"{head}{STOPPING} ; then
	deb-systemd-invoke stop {BFF_SERVICE} >/dev/null || true
fi
"#
    );
    let postrm = format!(
        r#"{head}if [ "$1" = remove ] && [ -d /run/systemd/system ] ; then
	systemctl --system daemon-reload >/dev/null || true
fi

if [ "$1" = "purge" ]; then
	if [ -x "/usr/bin/deb-systemd-helper" ]; then
		deb-systemd-helper purge {BFF_SERVICE} >/dev/null || true
	fi
fi
"#
    );
    vec![("postinst", postinst), ("prerm", prerm), ("postrm", postrm)]
}

/// The test that opens a prerm's stop: before the package's files are
/// replaced (deb-prerm(5): `upgrade`, `remove`, `deconfigure`), never in a
/// chroot install or without systemd running.
const STOPPING: &str = r#"if [ -z "$DPKG_ROOT" ] && { [ "$1" = upgrade ] || [ "$1" = remove ] || [ "$1" = deconfigure ] ; } && [ -d /run/systemd/system ]"#;

/// Records the active instances in [`RECORD`], one unit per line, and stops
/// them: the body of the engine's prerm and `.rpm` %pre.
fn record_and_stop_instances(indent: &str) -> String {
    format!(
        "{indent}systemctl list-units --plain --no-legend --state=active {INSTANCES} | while read -r unit _; do echo \"$unit\"; done > {RECORD} || true\n\
         {indent}systemctl stop {INSTANCES} >/dev/null || true\n"
    )
}

/// Starts each instance [`RECORD`] names: the body of the engine's postinst
/// and `.rpm` %posttrans.
fn start_recorded_instances(indent: &str) -> String {
    format!(
        "{indent}if [ -f {RECORD} ]; then\n\
         {indent}\twhile read -r unit; do\n\
         {indent}\t\tsystemctl start \"$unit\" >/dev/null || true\n\
         {indent}\tdone < {RECORD}\n\
         {indent}fi\n"
    )
}

/// Copies each shipped default into [`ENGINE_ETC`] when it is missing, never
/// over an existing file: the server file 0640 with the group private-ai
/// once that group exists (the core package creates it), else 0644 root:root
/// until the manager's first write; the model profiles, the assignment and
/// the instance record 0644, as none of them holds a secret. With `chroot` (the
/// `.deb`), every path is under `$DPKG_ROOT` and a chroot install asks the
/// host for no group: the server file is copied 0644 there.
fn copy_missing_defaults(indent: &str, chroot: bool) -> String {
    let server = "server@default.ini";
    let model_profiles = "models.ini";
    let assignments = "assignments.ini";
    let instances = "instances.ini";
    let (root, host) = if chroot {
        ("$DPKG_ROOT", r#"[ -z "$DPKG_ROOT" ] && "#)
    } else {
        ("", "")
    };
    let etc = format!("\"{root}{ENGINE_ETC}\"");
    let share = format!("\"{root}{ENGINE_DEFAULTS}\"");
    format!(
        "{indent}install -d -m 0755 {etc}\n\
         {indent}if [ ! -e {etc}/{server} ]; then\n\
         {indent}\tif {host}getent group private-ai >/dev/null; then\n\
         {indent}\t\tinstall -m 0640 -g private-ai {share}/{server} {etc}/{server}\n\
         {indent}\telse\n\
         {indent}\t\tinstall -m 0644 {share}/{server} {etc}/{server}\n\
         {indent}\tfi\n\
         {indent}fi\n\
         {indent}if [ ! -e {etc}/{model_profiles} ]; then\n\
         {indent}\tinstall -m 0644 {share}/{model_profiles} {etc}/{model_profiles}\n\
         {indent}fi\n\
         {indent}if [ ! -e {etc}/{assignments} ]; then\n\
         {indent}\tinstall -m 0644 {share}/{assignments} {etc}/{assignments}\n\
         {indent}fi\n\
         {indent}if [ ! -e {etc}/{instances} ]; then\n\
         {indent}\tinstall -m 0644 {share}/{instances} {etc}/{instances}\n\
         {indent}fi\n"
    )
}

/// The engine's `.deb` maintainer scripts: its running instances recorded
/// and stopped before its files are replaced, and started again, each by
/// name, once the new files are in place; the record forgotten on removal.
/// On configure the missing defaults are copied first; a purge deletes the
/// engine's configuration and the instances' enablement links (dangling by
/// then: deb-systemd-helper knows no instance the manager enabled), a
/// removal keeps both.
fn engine_deb_scripts() -> Vec<(&'static str, String)> {
    let head = format!("#!/bin/sh\nset -e\n{}\n", header_of(Component::Llama, "#"));
    let postinst = format!(
        r#"{head}if [ "$1" = "configure" ] || [ "$1" = "abort-upgrade" ] || [ "$1" = "abort-deconfigure" ] || [ "$1" = "abort-remove" ] ; then
	if [ "$1" = "configure" ]; then
{copy}{tmpfiles}	fi
	if [ -d /run/systemd/system ]; then
		systemctl --system daemon-reload >/dev/null || true
{start}	fi
	if [ -z "$DPKG_ROOT" ]; then
		rm -f {RECORD}
	fi
fi
"#,
        copy = copy_missing_defaults("\t\t", true),
        tmpfiles = deb_create_tmpfiles("\t\t"),
        start = start_recorded_instances("\t\t")
    );
    let prerm = format!(
        "{head}{STOPPING} ; then\n{}fi\n",
        record_and_stop_instances("\t")
    );
    let postrm = format!(
        r#"{head}if [ "$1" = remove ]; then
	rm -f {RECORD}
	if [ -d /run/systemd/system ]; then
		systemctl --system daemon-reload >/dev/null || true
	fi
fi

if [ "$1" = "purge" ]; then
	rm -rf "$DPKG_ROOT{ENGINE_ETC}"
	rm -f "$DPKG_ROOT{INSTANCE_LINKS}"*.service
fi
"#
    );
    vec![("postinst", postinst), ("prerm", prerm), ("postrm", postrm)]
}

/// Writes [`deb_scripts`] into `root/DEBIAN`, mode 0755, and for the core
/// its PAM service with the `.deb` text, declared in `DEBIAN/conffiles`.
pub fn write_deb_scripts(root: &Path, c: Component) -> Result<()> {
    let scripts = deb_scripts(c);
    if scripts.is_empty() {
        return Ok(());
    }
    let dir = root.join("DEBIAN");
    std::fs::create_dir_all(&dir)?;
    for (name, text) in scripts {
        let p = dir.join(name);
        std::fs::write(&p, text).with_context(|| format!("writing {}", p.display()))?;
        set_mode(&p, 0o755)?;
    }
    if c == Component::Core {
        write_pam(root, &pam_deb())?;
        let p = dir.join("conffiles");
        std::fs::write(&p, format!("/{PAM_SERVICE}\n"))
            .with_context(|| format!("writing {}", p.display()))?;
        set_mode(&p, 0o644)?;
    }
    Ok(())
}

/// The `.deb` Depends the maintainer scripts need, empty when none.
pub fn deb_depends(c: Component) -> &'static str {
    // What dh_installsysusers adds for systemd-sysusers; deb-systemd-helper
    // and deb-systemd-invoke come with init-system-helpers, which is Essential.
    if c == Component::Core || c == Component::Bff {
        "systemd | systemd-standalone-sysusers | systemd-sysusers"
    } else {
        ""
    }
}

/// The `.rpm` scriptlets of a package (`%post`, `%preun`, `%postun`,
/// `%posttrans`), empty for a package without system files.
pub fn rpm_scriptlets(c: Component) -> String {
    if c == Component::Bff {
        return bff_rpm_scriptlets();
    }
    if c == Component::Llama {
        return engine_rpm_scriptlets();
    }
    if c != Component::Core {
        return String::new();
    }
    // Fedora's systemd macros (systemd's src/rpm/macros.systemd.in) written
    // out, since they are not defined where the packages are built. The
    // manager is stopped in the new package's %pre on an upgrade, enabled
    // on the first install, and (re)started in %posttrans, once the old
    // package's files are gone.
    format!(
        r#"%pre
if [ $1 -ge 2 ] && [ -d /run/systemd/system ]; then
    systemctl stop {MANAGER_SERVICE} || :
fi

%post
systemd-sysusers private-ai.conf || :
if [ $1 -eq 1 ]; then
    systemctl enable {MANAGER_SERVICE} || :
fi

%preun
if [ $1 -eq 0 ]; then
    if [ -d /run/systemd/system ]; then
        systemctl disable --now {MANAGER_SERVICE} || :
    else
        systemctl disable {MANAGER_SERVICE} || :
    fi
fi

%postun
if [ -d /run/systemd/system ]; then
    systemctl daemon-reload || :
fi

%posttrans
if [ -d /run/systemd/system ]; then
    systemctl daemon-reload || :
    {RELOAD_BUS} || :
    if systemctl is-enabled --quiet {MANAGER_SERVICE}; then
        systemctl restart {MANAGER_SERVICE} || :
    fi
fi

"#
    )
}

