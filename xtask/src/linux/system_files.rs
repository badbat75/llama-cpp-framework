    /// The `<defaults>` of action `id`: (allow_any, allow_inactive, allow_active).
    fn defaults(text: &str, id: &str) -> (String, String, String) {
        let action = between(text, &format!(r#"<action id="{id}">"#), "</action>");
        for tag in ["description", "message"] {
            let value = between(action, &format!("<{tag}>"), &format!("</{tag}>"));
            assert!(!value.trim().is_empty(), "{id}: empty {tag}");
        }
        let d = between(action, "<defaults>", "</defaults>");
        let get = |tag: &str| {
            between(d, &format!("<{tag}>"), &format!("</{tag}>"))
                .trim()
                .to_string()
        };
        (get("allow_any"), get("allow_inactive"), get("allow_active"))
    }

