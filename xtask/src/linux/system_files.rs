    /// The bff's `.deb` postinst, as dh_installsystemd writes it for one
    /// unit (debhelper's autoscripts postinst-systemd-enable and
    /// postinst-systemd-restart): on configure the unit enabled unless the
    /// administrator disabled it, then, with systemd running, a
    /// daemon-reload and a start on an install or a restart on an upgrade.
    /// No user to create (DynamicUser=), no bus policy to reload, nothing of
    /// the manager's or the instances'. The header names the bff's package.
    #[test]
    fn the_bff_deb_postinst_enables_and_starts_the_bff() {
        let scripts = deb_scripts(Component::Bff);
        let text = &scripts
            .iter()
            .find(|(n, _)| *n == "postinst")
            .expect("a postinst")
            .1;
        let configure = at(
            text,
            r#"if [ "$1" = "configure" ] || [ "$1" = "abort-upgrade" ] || [ "$1" = "abort-deconfigure" ] || [ "$1" = "abort-remove" ] ; then"#,
        );
        let was = at(
            text,
            "deb-systemd-helper --quiet was-enabled private-ai-bff.service",
        );
        at(
            text,
            "deb-systemd-helper enable private-ai-bff.service >/dev/null || true",
        );
        at(
            text,
            "deb-systemd-helper update-state private-ai-bff.service >/dev/null || true",
        );
        let running = at(text, "if [ -d /run/systemd/system ]; then");
        let reload = at(text, "systemctl --system daemon-reload >/dev/null || true");
        let upgrade = at(text, r#"if [ -n "$2" ]; then"#);
        let restart = at(
            text,
            "deb-systemd-invoke restart private-ai-bff.service >/dev/null || true",
        );
        let start = at(
            text,
            "deb-systemd-invoke start private-ai-bff.service >/dev/null || true",
        );
        assert!(configure < was && was < running, "{text}");
        assert!(running < reload && reload < upgrade, "{text}");
        assert!(upgrade < restart && restart < start, "{text}");
        assert!(text.contains("private-ai-framework-bff"), "{text}");
        for other in [
            "systemd-sysusers",
            "busctl",
            "private-ai-manager",
            "llama.cpp@",
            "private-ai-framework-llama",
        ] {
            assert!(
                !text.contains(other),
                "{other} in the bff's postinst:\n{text}"
            );
        }
    }

    /// prerm stops the bff on a removal only (an upgrade keeps it running
    /// until postinst restarts it: prerm-systemd-restart); postrm reloads
    /// systemd after a removal and forgets the enablement on purge
    /// (postrm-systemd-reload-only, postrm-systemd). Nothing is deleted.
    #[test]
    fn the_bff_deb_prerm_and_postrm_stop_it_on_removal() {
        let scripts = deb_scripts(Component::Bff);
        let prerm = &scripts
            .iter()
            .find(|(n, _)| *n == "prerm")
            .expect("a prerm")
            .1;
        let remove = at(
            prerm,
            r#"if [ -z "$DPKG_ROOT" ] && [ "$1" = remove ] && [ -d /run/systemd/system ] ; then"#,
        );
        let stop = at(
            prerm,
            "deb-systemd-invoke stop private-ai-bff.service >/dev/null || true",
        );
        assert!(remove < stop, "{prerm}");

        let postrm = &scripts
            .iter()
            .find(|(n, _)| *n == "postrm")
            .expect("a postrm")
            .1;
        let removed = at(
            postrm,
            r#"if [ "$1" = remove ] && [ -d /run/systemd/system ] ; then"#,
        );
        let reload = at(
            postrm,
            "systemctl --system daemon-reload >/dev/null || true",
        );
        assert!(removed < reload, "{postrm}");
        let purge = at(postrm, r#"if [ "$1" = "purge" ]; then"#);
        let forget = at(
            postrm,
            "deb-systemd-helper purge private-ai-bff.service >/dev/null || true",
        );
        assert!(purge < forget, "{postrm}");
        for (name, text) in &scripts {
            for other in ["private-ai-manager", "llama.cpp@", "/etc/private-ai", "rm "] {
                assert!(!text.contains(other), "{name} names {other}:\n{text}");
            }
        }
    }

