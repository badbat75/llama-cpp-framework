    /// The bff's `.rpm` scriptlets, the same shape as the manager's
    /// (Fedora's systemd macros written out): enabled on the first install,
    /// disabled and stopped on the last removal, a daemon-reload after a
    /// removal, and in %posttrans a daemon-reload and a restart of the bff
    /// when it is enabled, so an administrator's disable holds. Nothing of
    /// the manager's, the instances' or the bus.
    #[test]
    fn the_bff_rpm_scriptlets_enable_start_and_stop_the_bff() {
        let text = rpm_scriptlets(Component::Bff);
        let names: Vec<&str> = text
            .lines()
            .filter(|l| l.starts_with('%'))
            .map(str::trim)
            .collect();
        assert_eq!(
            names,
            ["%post", "%preun", "%postun", "%posttrans"],
            "{text}"
        );

        let post = scriptlet(&text, "%post");
        let first = at(&post, "if [ $1 -eq 1 ]; then");
        let enable = at(&post, "systemctl enable private-ai-bff.service || :");
        assert!(first < enable, "{post}");

        let preun = scriptlet(&text, "%preun");
        let removal = at(&preun, "if [ $1 -eq 0 ]");
        let disable = at(
            &preun,
            "systemctl disable --now private-ai-bff.service || :",
        );
        assert!(removal < disable, "{preun}");

        let postun = scriptlet(&text, "%postun");
        at(&postun, "systemctl daemon-reload || :");

        let posttrans = scriptlet(&text, "%posttrans");
        let reload = at(&posttrans, "systemctl daemon-reload || :");
        let enabled = at(
            &posttrans,
            "if systemctl is-enabled --quiet private-ai-bff.service; then",
        );
        let restart = at(&posttrans, "systemctl restart private-ai-bff.service || :");
        assert!(reload < enabled && enabled < restart, "{posttrans}");

        for name in ["%post", "%preun", "%postun", "%posttrans"] {
            parses(name, &scriptlet(&text, name));
        }
        for other in [
            "systemd-sysusers",
            "busctl",
            "private-ai-manager",
            "llama.cpp@",
            "/etc/private-ai",
            "rm ",
        ] {
            assert!(!text.contains(other), "{other} in:\n{text}");
        }
    }
