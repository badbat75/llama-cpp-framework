    // ── The scripts run, with fake system tools ─────────────────────────

    /// Where the engine's scripts record the instances that were running
    /// before an upgrade, one unit name per line, for the scripts that run
    /// after the new files are in place. Under /run: a tmpfs, emptied at
    /// boot, when the enabled instances start on their own anyway. A file
    /// named after the package directly in /run rather than a directory:
    /// no unit's RuntimeDirectory= (which systemd removes when that unit
    /// stops) can own or clean it, and there is nothing to create first.
    const RECORD: &str = "/run/llama.cpp.instances";

    /// The engine's configuration directory, where the instance files live
    /// (`paths::engine_config_dir` in pai-core).
    const ENGINE_ETC: &str = "/etc/llama.cpp";
    /// Where the engine's package ships the defaults, read-only.
    const ENGINE_DEFAULTS: &str = "/usr/share/private-ai/llama.cpp";
    /// The sandbox's stand-in for the shipped server file (the real one is
    /// pinned by `the_engine_ships_its_defaults_read_only`).
    const SHIPPED_SERVER: &str = "[Server]\nPort = 9931\nHostname = 127.0.0.1\n";

    /// What `systemctl list-units --plain --no-legend --state=active
    /// 'llama.cpp@*.service'` printed on a machine with an instance running
    /// (Ubuntu 26.04, systemd 259), with a second instance added.
    const ACTIVE: &str = "llama.cpp@default.service  loaded active running llama.cpp server default (Private AI Framework)\n\
                          llama.cpp@gpu1.service     loaded active running llama.cpp server gpu1 (Private AI Framework)\n";

    /// A scratch directory with fake `systemctl`, `deb-systemd-invoke`,
    /// `deb-systemd-helper`, `systemd-sysusers` and `busctl`, each logging
    /// its name and arguments, a line per call; the fake systemctl answers
    /// `list-units` with the lines in `active` and every other call with
    /// success (`is-enabled` included).
    struct Sandbox {
        dir: std::path::PathBuf,
    }

    impl Sandbox {
        fn new(name: &str) -> Sandbox {
            use std::os::unix::fs::PermissionsExt;
            let dir =
                std::env::temp_dir().join(format!("xtask-scripts-{name}-{}", std::process::id()));
            let _ = std::fs::remove_dir_all(&dir);
            let bin = dir.join("bin");
            std::fs::create_dir_all(&bin).unwrap();
            std::fs::create_dir_all(dir.join("systemd")).unwrap();
            let log = dir.join("log");
            for tool in [
                "systemctl",
                "deb-systemd-invoke",
                "deb-systemd-helper",
                "systemd-sysusers",
                "busctl",
                "chown",
                "chgrp",
            ] {
                let mut body = if tool == "systemctl" {
                    // Each call says whether the engine's server file is in
                    // place at that moment (`has-default=yes|no`).
                    format!(
                        "#!/bin/sh\nif [ -f \"{}\" ]; then d=yes; else d=no; fi\n\
                         echo \"{tool} $* has-default=$d\" >> \"{}\"\n",
                        dir.join("etc-engine").join("server@default.ini").display(),
                        log.display()
                    )
                } else {
                    format!("#!/bin/sh\necho \"{tool} $*\" >> \"{}\"\n", log.display())
                };
                if tool == "systemctl" {
                    body.push_str(&format!(
                        "case \" $* \" in *\" list-units \"*) cat \"{}\" 2>/dev/null ;; esac\n",
                        dir.join("active").display()
                    ));
                }
                body.push_str("exit 0\n");
                let p = bin.join(tool);
                std::fs::write(&p, body).unwrap();
                std::fs::set_permissions(&p, std::fs::Permissions::from_mode(0o755)).unwrap();
            }
            // getent: the group private-ai exists only once `set_group(true)`.
            let getent = format!(
                "#!/bin/sh\necho \"getent $*\" >> \"{log}\"\n\
                 if [ \"$1\" = group ] && [ \"$2\" = private-ai ] && [ -f \"{flag}\" ]; then\n\
                 \techo 'private-ai:x:990:'\n\texit 0\nfi\nexit 2\n",
                log = log.display(),
                flag = dir.join("group-exists").display()
            );
            // install(1) without the chown a non-root user may not make:
            // logs its arguments, copies (or makes directories) and applies
            // -m; -g and -o are only logged.
            let install = format!(
                "#!/bin/sh\necho \"install $*\" >> \"{log}\"\n{}",
                r#"mode=""; dir=0; parents=0; files=""
while [ $# -gt 0 ]; do
	case "$1" in
		-m|--mode) mode="$2"; shift 2 ;;
		--mode=*) mode="${1#--mode=}"; shift ;;
		-dm*) dir=1; mode="${1#-dm}"; shift ;;
		-Dm*) parents=1; mode="${1#-Dm}"; shift ;;
		-m*) mode="${1#-m}"; shift ;;
		-g|-o|--group|--owner) shift 2 ;;
		-d|--directory) dir=1; shift ;;
		-D) parents=1; shift ;;
		-*) shift ;;
		*) files="$files $1"; shift ;;
	esac
done
if [ "$dir" = 1 ]; then
	for d in $files; do mkdir -p "$d" || exit 1; if [ -n "$mode" ]; then chmod "$mode" "$d"; fi; done
	exit 0
fi
set -- $files
src="$1"; eval dst=\${$#}
if [ -d "$dst" ]; then dst="$dst/$(basename "$src")"; fi
if [ "$parents" = 1 ]; then mkdir -p "$(dirname "$dst")"; fi
cp "$src" "$dst" || exit 1
if [ -n "$mode" ]; then chmod "$mode" "$dst"; fi
exit 0
"#,
                log = log.display()
            );
            for (tool, body) in [("getent", getent), ("install", install)] {
                let p = bin.join(tool);
                std::fs::write(&p, body).unwrap();
                std::fs::set_permissions(&p, std::fs::Permissions::from_mode(0o755)).unwrap();
            }
            // The engine's shipped defaults, as the package installs them.
            let share = dir.join("share-engine");
            std::fs::create_dir_all(&share).unwrap();
            std::fs::write(share.join("server@default.ini"), SHIPPED_SERVER).unwrap();
            std::fs::write(share.join("presets.ini"), "").unwrap();
            Sandbox { dir }
        }

        fn record(&self) -> std::path::PathBuf {
            self.dir.join("record")
        }

        /// The sandbox's `/etc/llama.cpp`.
        fn etc(&self) -> std::path::PathBuf {
            self.dir.join("etc-engine")
        }

        /// Whether the group private-ai exists, for the fake getent.
        fn set_group(&self, exists: bool) {
            let flag = self.dir.join("group-exists");
            if exists {
                std::fs::write(flag, "").unwrap();
            } else {
                let _ = std::fs::remove_file(flag);
            }
        }

        fn set_active(&self, text: &str) {
            std::fs::write(self.dir.join("active"), text).unwrap();
        }

        /// The recorded unit names, None when there is no record.
        fn recorded(&self) -> Option<Vec<String>> {
            std::fs::read_to_string(self.record()).ok().map(|t| {
                t.lines()
                    .map(str::trim)
                    .filter(|l| !l.is_empty())
                    .map(String::from)
                    .collect()
            })
        }

        /// Runs `script` with `args`, its /run paths moved into the
        /// sandbox (systemd running unless `systemd` is false), and returns
        /// the calls the fakes logged by this run.
        fn run(
            &self,
            script: &str,
            args: &[&str],
            systemd: bool,
            dpkg_root: Option<&str>,
        ) -> Vec<String> {
            let systemd_dir = if systemd {
                self.dir.join("systemd")
            } else {
                self.dir.join("no-systemd")
            };
            let text = script
                .replace(RECORD, &self.record().display().to_string())
                .replace("/run/systemd/system", &systemd_dir.display().to_string())
                .replace(
                    ENGINE_DEFAULTS,
                    &self.dir.join("share-engine").display().to_string(),
                )
                .replace(ENGINE_ETC, &self.etc().display().to_string());
            // Nothing may reach the real system: every /run, /etc and
            // /usr/share/private-ai path is moved, and the tools are called
            // through PATH only.
            assert!(
                !text.contains("/run/"),
                "a /run path the test does not move:\n{script}"
            );
            for real in ["/etc/", "/usr/share/private-ai"] {
                assert!(
                    !text.contains(real),
                    "a {real} path the test does not move:\n{script}"
                );
            }
            self.exec(&text, script, args, dpkg_root)
        }

        /// Runs `script` as dpkg runs it for a chroot install: `DPKG_ROOT`
        /// set to `root` (a directory of the sandbox) and the engine's
        /// paths left as they are, so the script must reach them through
        /// `$DPKG_ROOT`. Refused before it runs when one of them is not
        /// prefixed with it, so the host's /etc is never written. The /run
        /// paths are moved as in [`Sandbox::run`], systemd running.
        fn run_chroot(&self, script: &str, args: &[&str], root: &std::path::Path) -> Vec<String> {
            let text = script
                .replace(RECORD, &self.record().display().to_string())
                .replace(
                    "/run/systemd/system",
                    &self.dir.join("systemd").display().to_string(),
                );
            assert!(
                !text.contains("/run/"),
                "a /run path the test does not move:\n{script}"
            );
            let mut rest = text.clone();
            for path in [ENGINE_ETC, ENGINE_DEFAULTS] {
                for prefix in ["${DPKG_ROOT}", "$DPKG_ROOT"] {
                    rest = rest.replace(&format!("{prefix}{path}"), "<root>");
                }
            }
            for real in ["/etc/", "/usr/share/private-ai"] {
                assert!(
                    !rest.contains(real),
                    "a {real} path not under $DPKG_ROOT in a chroot install:\n{script}"
                );
            }
            self.exec(&text, script, args, Some(&root.display().to_string()))
        }

        /// Writes `text` (the moved `script`) and runs it with `args` and
        /// the fakes first on PATH; returns the calls they logged.
        fn exec(
            &self,
            text: &str,
            script: &str,
            args: &[&str],
            dpkg_root: Option<&str>,
        ) -> Vec<String> {
            for abs in [
                "/bin/systemctl",
                "/usr/bin/deb-systemd",
                "/usr/bin/busctl",
                "/bin/install",
                "/bin/chown",
                "/bin/chgrp",
                "/bin/getent",
            ] {
                assert!(!text.contains(abs), "{abs} bypasses the fakes:\n{script}");
            }
            let file = self.dir.join("script");
            std::fs::write(&file, text).unwrap();
            let log = self.dir.join("log");
            let _ = std::fs::remove_file(&log);
            let mut cmd = std::process::Command::new("sh");
            cmd.arg(&file)
                .args(args)
                .env(
                    "PATH",
                    format!("{}:/usr/bin:/bin", self.dir.join("bin").display()),
                )
                .env_remove("DPKG_ROOT");
            if let Some(root) = dpkg_root {
                cmd.env("DPKG_ROOT", root);
            }
            let out = cmd.output().unwrap();
            assert!(
                out.status.success(),
                "{args:?} failed: {}\n{text}",
                String::from_utf8_lossy(&out.stderr)
            );
            std::fs::read_to_string(&log)
                .unwrap_or_default()
                .lines()
                .map(String::from)
                .collect()
        }
    }

    impl Drop for Sandbox {
        fn drop(&mut self) {
            let _ = std::fs::remove_dir_all(&self.dir);
        }
    }

    fn deb(c: Component, name: &str) -> String {
        deb_scripts(c)
            .into_iter()
            .find(|(n, _)| *n == name)
            .unwrap_or_else(|| panic!("{c:?} has no {name}"))
            .1
    }

    /// The index of the first call whose words hold every one of `words`.
    fn call(log: &[String], words: &[&str]) -> Option<usize> {
        log.iter().position(|l| {
            let w: Vec<&str> = l.split_whitespace().collect();
            words.iter().all(|x| w.contains(x))
        })
    }

    /// Whether a call starts (or restarts) `unit`.
    fn starts(log: &[String], unit: &str) -> bool {
        call(log, &["start", unit]).is_some() || call(log, &["restart", unit]).is_some()
    }

    /// Whether any call starts or restarts an instance.
    fn starts_an_instance(log: &[String]) -> bool {
        log.iter().any(|l| {
            let w: Vec<&str> = l.split_whitespace().collect();
            (w.contains(&"start") || w.contains(&"restart") || w.contains(&"try-restart"))
                && l.contains("llama.cpp@")
        })
    }

    /// Whether a call stops the instances (by pattern or by name).
    fn stop_instances(log: &[String]) -> Option<usize> {
        log.iter()
            .position(|l| l.split_whitespace().any(|w| w == "stop") && l.contains("llama.cpp@"))
    }

    /// The engine's prerm, before its files are replaced (deb-prerm(5):
    /// `prerm upgrade <new-version>`, `prerm remove`, `prerm deconfigure
    /// in-favour <package> <version>`): it records the active instances,
    /// one unit name per line, then stops them. `failed-upgrade` (the new
    /// package's prerm, after the old one failed) does nothing, nor does a
    /// chroot install (`DPKG_ROOT`) or a system without systemd running.
    #[test]
    fn the_engine_prerm_records_the_running_instances_and_stops_them() {
        let prerm = deb(Component::Llama, "prerm");
        for args in [
            &["upgrade", "1:1.0.1+pai1"][..],
            &["remove"][..],
            &["deconfigure", "in-favour", "llama-cpp-other", "1.0"][..],
        ] {
            let sb = Sandbox::new("engine-prerm");
            sb.set_active(ACTIVE);
            let log = sb.run(&prerm, args, true, None);
            assert_eq!(
                sb.recorded(),
                Some(vec![
                    "llama.cpp@default.service".to_string(),
                    "llama.cpp@gpu1.service".to_string()
                ]),
                "{args:?}: {log:?}"
            );
            let listed = call(&log, &["list-units"]).unwrap_or_else(|| panic!("{args:?}: {log:?}"));
            let stopped = stop_instances(&log).unwrap_or_else(|| panic!("{args:?}: {log:?}"));
            assert!(listed < stopped, "recorded before the stop: {log:?}");
            assert!(!starts_an_instance(&log), "{log:?}");
        }
        for (args, systemd, root) in [
            (
                &["failed-upgrade", "1:1.0.0+pai1", "1:1.0.1+pai1"][..],
                true,
                None,
            ),
            (&["upgrade", "1:1.0.1+pai1"][..], true, Some("/srv/chroot")),
            (&["upgrade", "1:1.0.1+pai1"][..], false, None),
        ] {
            let sb = Sandbox::new("engine-prerm-none");
            sb.set_active(ACTIVE);
            let log = sb.run(&prerm, args, systemd, root);
            assert_eq!(
                stop_instances(&log),
                None,
                "{args:?} {systemd} {root:?}: {log:?}"
            );
            assert_eq!(sb.recorded(), None, "{args:?} {systemd} {root:?}");
        }
    }

