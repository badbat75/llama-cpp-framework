    /// What the rules file answers, run by node (a prerequisite of the
    /// build, `configure.rs`) against a stand-in `polkit` object with
    /// polkit(8)'s `polkit.Result` values: for each (action id, the
    /// subject's groups), the value of the first rule that returns one, or
    /// `null` when none does (`NOT_HANDLED`, so polkit falls back to the
    /// action's defaults).
    fn rules_answer(rules: &str, cases: &[(&str, &[&str])]) -> Vec<String> {
        use std::io::Write;
        let cases_js: Vec<String> = cases
            .iter()
            .map(|(id, groups)| {
                let g: Vec<String> = groups.iter().map(|g| format!("{g:?}")).collect();
                format!("[{id:?}, [{}]]", g.join(", "))
            })
            .collect();
        let script = format!(
            "var rules = [];\n\
             var polkit = {{\n\
               Result: {{ NO: 'no', YES: 'yes', AUTH_SELF: 'auth_self', AUTH_SELF_KEEP: 'auth_self_keep',\n\
                          AUTH_ADMIN: 'auth_admin', AUTH_ADMIN_KEEP: 'auth_admin_keep', NOT_HANDLED: null }},\n\
               addRule: function (f) {{ rules.push(f); }},\n\
               addAdminRule: function (f) {{}},\n\
               log: function (m) {{}}\n\
             }};\n\
             {rules}\n\
             var cases = [{}];\n\
             cases.forEach(function (c) {{\n\
               var action = {{ id: c[0], lookup: function (k) {{ return undefined; }} }};\n\
               var subject = {{ user: 'someone', local: true, active: true,\n\
                 isInGroup: function (g) {{ return c[1].indexOf(g) >= 0; }},\n\
                 isInNetGroup: function (g) {{ return false; }} }};\n\
               var r = null;\n\
               for (var i = 0; i < rules.length && r === null; i++) {{\n\
                 var v = rules[i](action, subject);\n\
                 if (v !== null && v !== undefined) {{ r = v; }}\n\
               }}\n\
               console.log(r === null ? 'null' : r);\n\
             }});\n",
            cases_js.join(", ")
        );
        let mut child = std::process::Command::new("node")
            .arg("-")
            .stdin(std::process::Stdio::piped())
            .stdout(std::process::Stdio::piped())
            .stderr(std::process::Stdio::piped())
            .spawn()
            .expect("node, a prerequisite of the build, runs");
        child
            .stdin
            .take()
            .unwrap()
            .write_all(script.as_bytes())
            .unwrap();
        let out = child.wait_with_output().unwrap();
        assert!(
            out.status.success(),
            "the rules do not run:\n{}\n{rules}",
            String::from_utf8_lossy(&out.stderr)
        );
        String::from_utf8(out.stdout)
            .unwrap()
            .lines()
            .map(str::to_string)
            .collect()
    }

