//! The system files the `-llama` package ships so the manager and the
//! instances run as services: the two systemd units, the D-Bus policy of
//! the manager's bus name, the polkit actions it checks, the sysusers.d
//! entry of the service user, and the maintainer scripts that create the
//! user and enable, start and stop the manager; and the unit of the web
//! service with its maintainer scripts, which the `-bff` package ships.

use crate::common::components::Component;
use crate::common::configurator::set_mode;
use anyhow::{Context, Result};
use std::path::Path;

/// Where the package places pai-manager (`package::place`), which the units
/// call by full path.
const MANAGER_EXE: &str = "/usr/libexec/private-ai/pai-manager";
/// The manager's bus name (`dbus::BUS_NAME` in the manager).
const BUS_NAME: &str = "org.privateai.Manager1";
/// The manager's unit.
const MANAGER_SERVICE: &str = "private-ai-manager.service";
/// Where the package places pai-bff (`package::place`).
const BFF_EXE: &str = "/usr/libexec/private-ai/pai-bff";
/// The web service's unit.
const BFF_SERVICE: &str = "private-ai-bff.service";
/// Every instance's unit, for systemctl.
const INSTANCES: &str = "'llama.cpp@*.service'";
/// Asks the system bus to read its policies again.
const RELOAD_BUS: &str =
    "busctl call org.freedesktop.DBus /org/freedesktop/DBus org.freedesktop.DBus ReloadConfig";

/// The header of every generated file of the llama.cpp package, behind the
/// comment marker `mark`.
fn header(mark: &str) -> String {
    header_of(Component::Llama, mark)
}

/// The header of a generated file of package `c`.
fn header_of(c: Component, mark: &str) -> String {
    format!(
        "{mark} Installed by the {} package, generated by its package phase\n\
         {mark} (xtask/src/linux/system_files.rs). Overwritten on every upgrade.\n",
        c.package()
    )
}

/// The system files, by path under the package root, with their text.
pub fn files() -> Vec<(&'static str, String)> {
    vec![
        (
            "usr/lib/systemd/system/private-ai-manager.service",
            manager_unit(),
        ),
        ("usr/lib/systemd/system/llama.cpp@.service", instance_unit()),
        (
            "usr/share/dbus-1/system.d/org.privateai.Manager1.conf",
            dbus_policy(),
        ),
        (
            "usr/share/polkit-1/actions/org.privateai.manager.policy",
            polkit_policy(),
        ),
        ("usr/lib/sysusers.d/private-ai.conf", sysusers()),
        ("usr/lib/systemd/system/private-ai-bff.service", bff_unit()),
    ]
}

/// `private-ai-manager.service`: `pai-manager serve`, as root.
pub fn manager_unit() -> String {
    format!(
        "{}# Local changes go in a drop-in: systemctl edit {MANAGER_SERVICE}\n\
         \n\
         [Unit]\n\
         Description=Private AI Framework manager\n\
         \n\
         [Service]\n\
         Type=dbus\n\
         BusName={BUS_NAME}\n\
         ExecStart={MANAGER_EXE} serve\n\
         # The services' home: a blank ModelsDir means the same to the manager as to the instances.\n\
         Environment=HOME=/var/lib/private-ai\n\
         ConfigurationDirectory=private-ai\n\
         ConfigurationDirectoryMode=0755\n\
         Restart=on-failure\n\
         \n\
         [Install]\n\
         WantedBy=multi-user.target\n",
        header("#")
    )
}

/// `llama.cpp@.service`: `pai-manager run-instance %i`, as the service user.
pub fn instance_unit() -> String {
    format!(
        "{}# Started by the manager, at boot included; never enabled on its own.\n\
         \n\
         [Unit]\n\
         Description=llama.cpp server %i (Private AI Framework)\n\
         After=network-online.target\n\
         Wants=network-online.target\n\
         \n\
         [Service]\n\
         Type=exec\n\
         User=private-ai\n\
         Group=private-ai\n\
         SupplementaryGroups=render video\n\
         # The user's home and the launcher's data root under it.\n\
         StateDirectory=private-ai private-ai/.local/share/private-ai\n\
         StateDirectoryMode=0750\n\
         ExecStart={MANAGER_EXE} run-instance %i\n\
         Restart=on-abnormal\n\
         RestartSec=5\n",
        header("#")
    )
}

