    /// The lines of one `[Section]` of a unit file, comments and blanks left out.
    fn section<'a>(unit: &'a str, name: &str) -> Vec<&'a str> {
        let mut inside = false;
        let mut out = Vec::new();
        for line in unit.lines().map(str::trim) {
            if line.starts_with('[') {
                inside = line == name;
                continue;
            }
            if inside && !line.is_empty() && !line.starts_with('#') && !line.starts_with(';') {
                out.push(line);
            }
        }
        out
    }

    /// The text between `open` and the next `close` after it.
    fn between<'a>(text: &'a str, open: &str, close: &str) -> &'a str {
        let start = text
            .find(open)
            .unwrap_or_else(|| panic!("{open} missing:\n{text}"))
            + open.len();
        let len = text[start..]
            .find(close)
            .unwrap_or_else(|| panic!("{close} after {open} missing:\n{text}"));
        &text[start..start + len]
    }

