//! build/macos/config-build.toml: the machine-derived half of the macOS
//! build, written by the configure phase and read by build and package.

use crate::common::util;
use anyhow::{Context, Result};
use serde::Deserialize;
use std::path::PathBuf;

#[derive(Deserialize, Default)]
pub struct BuildConfig {
    pub dist_root: String,
    pub llama_cpp_dir: String,
    pub build_type: String,
    pub c_compiler: String,
    pub cxx_compiler: String,
    pub build_jobs: u32,
}

pub fn path() -> PathBuf {
    util::build_root().join("config-build.toml")
}

/// The config, or None before the configure phase has run.
pub fn load_optional() -> Result<Option<BuildConfig>> {
    let p = path();
    if !p.exists() {
        return Ok(None);
    }
    let text = std::fs::read_to_string(&p).with_context(|| format!("reading {}", p.display()))?;
    Ok(Some(toml::from_str(&text).with_context(|| format!("parsing {}", p.display()))?))
}

pub fn load() -> Result<BuildConfig> {
    load_optional()?.context("build/macos/config-build.toml not found. Run cargo run -p xtask -- configure first.")
}

fn q(s: &str) -> String {
    toml::Value::String(s.to_string()).to_string()
}

impl BuildConfig {
    pub fn save(&self) -> Result<()> {
        let text = format!(
            r#"# Generated by the configure phase (cargo run -p xtask -- configure); re-run it to refresh.

# Paths
# dist_root: where the SDK dists live, <root>/<Name>/<Version>/macos. The
# build resolves the Vulkan SDK there itself. Change it with
# cargo run -p xtask -- configure --dist-root <path>, not by hand.
dist_root = {dist_root}
llama_cpp_dir = {llama}

# Build settings
build_type = {build_type}
# Apple's clang, from the Xcode Command Line Tools (xcrun --find).
c_compiler = {cc}
cxx_compiler = {cxx}
# Parallel build jobs: 3/4 of logical cores, never all of them, so at least
# one stays free during the build (0 = use all cores).
build_jobs = {jobs}
"#,
            dist_root = q(&self.dist_root),
            llama = q(&self.llama_cpp_dir),
            build_type = q(&self.build_type),
            cc = q(&self.c_compiler),
            cxx = q(&self.cxx_compiler),
            jobs = self.build_jobs,
        );
        let p = path();
        std::fs::create_dir_all(p.parent().unwrap())?;
        std::fs::write(&p, text).with_context(|| format!("writing {}", p.display()))
    }
}
